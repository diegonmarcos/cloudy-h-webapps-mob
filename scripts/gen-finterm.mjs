#!/usr/bin/env node
// gen-finterm.mjs — the web FinTerm's declarations, GENERATED from the Android app (cloudy-u-android ad_Capital-* folder, #1342).
//
//   node scripts/gen-finterm.mjs [--android <dir>] [--check] [--root <dir>]
//
// Reads (read-only) from the Android repo: <ad_ folder>/data/sources.json (the source catalog), data/dashboards.json (the dashboards,
// panels, fetch specs, placeholders), build.json ui.stacks (the entry -> dashboard mapping per tab, with each entry's subtitle) and the declared
// data files a panel reads through an `asset:` source (data/central-banks.json), embedded under `declared`.
// The fin-api mesh base is DERIVED from the vendored cloudy-u-containers declaration (scripts/fallback-services.json): never typed.
// Writes packages/cloudy-ui/nav/finterm.json (the web terminal's declarations) and finterm-app.json (just the app id, for the route matcher). `--check` fails when the committed file differs
// from a fresh render (CI drift guard, like gen-nav / gen-app-links).
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { need, readRaw, listDir, emit } from './lib/android-src.mjs';

// `--root <dir>` points the site-side inputs/outputs elsewhere (the unit test runs the generator in a sandbox)
const ri = process.argv.indexOf('--root');
const root = ri >= 0 ? resolve(process.argv[ri + 1]) : join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'packages/cloudy-ui/nav/finterm.json';
// the route matcher (client router manifest, shell JS budget) reads only this tiny file, never the 46 kB declarations
export const OUT_APP = 'packages/cloudy-ui/nav/finterm-app.json';
const HEADER = 'GENERATED by scripts/gen-finterm.mjs from cloudy-u-android ad_Capital-*/data/{sources,dashboards}.json + build.json ui.stacks and the cloudy-u-containers service declarations — DO NOT EDIT. Re-run: node scripts/gen-finterm.mjs';
export const TABS = ['fi', 'eq', 'ex', 'nw', 'pm'];

/** Deep copy without the `_doc*` prose keys (Android documentation, not data). */
export const strip = (v) => Array.isArray(v) ? v.map(strip)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, strip(x)]))
  : v;
/** URL slug of a dashboard id: yield_curves -> yield-curves, mp_70_30_DM_EM -> mp-70-30-dm-em. */
export const slugOf = (id) => id.toLowerCase().replace(/_/g, '-');

/** Pure: the Android declarations + the containers declaration -> the web file. Throws on any contradiction. */
export function buildFinterm({ sources, dashboards, build, services, appId, declared = {} }) {
  const fail = (m) => { throw new Error(m); };
  const stacks = build.ui?.stacks ?? fail('build.json has no ui.stacks');
  const byId = new Map(dashboards.dashboards.map((d) => [d.id, d]));
  const srcIds = new Set(sources.sources.map((s) => s.id));
  const tabStacks = {};
  const out = [];
  for (const tab of TABS) {
    tabStacks[tab] = (stacks[tab] ?? fail(`ui.stacks has no ${tab}`)).filter((e) => e.kind === 'dashboard' || e.kind === 'section_title')
      .map((e) => e.kind === 'section_title' ? { kind: 'section_title', title: e.title } : { kind: 'dashboard', title: e.title, subtitle: e.subtitle ?? '', dashboard: e.dashboard });
    for (const e of tabStacks[tab]) {
      if (e.kind !== 'dashboard') continue;
      const d = byId.get(e.dashboard) ?? fail(`${tab}/${e.title}: no dashboard ${e.dashboard}`);
      if (d.tab !== tab || d.entry !== e.title) fail(`${e.dashboard}: dashboards.json says ${d.tab}/${d.entry}, ui.stacks says ${tab}/${e.title}`);
      for (const p of d.panels) if (!srcIds.has(p.source)) fail(`${d.id}/${p.id}: unknown source ${p.source}`);
      out.push({ ...strip(d), slug: slugOf(d.id), subtitle: e.subtitle ?? '' });
    }
  }
  if (out.length !== byId.size) fail(`dashboards.json has ${byId.size} dashboards, ui.stacks maps ${out.length}`);
  // #1399 each tab's Homepage (ui.sections[].pages: Home first, then one per dashboard, one scrollable row) and the removed pages' redirects
  const homes = {};
  const secs = build.ui.sections;
  if (secs) {
    if (build.ui.nav_ui?.mode !== 'classic') fail(`ui.nav_ui.mode is ${build.ui.nav_ui?.mode}: only classic draws the one-row sub-page nav`);
    for (const tab of TABS) {
      const s = secs.find((x) => x.id === tab) ?? fail(`ui.sections has no ${tab}`);
      if ((s.nav_mode ?? 'horizontal_one_row') !== 'horizontal_one_row' || s.groups?.length) fail(`${tab}: the sub-page nav is not one row`);
      const pages = s.pages ?? [];
      if (pages[0]?.id !== `${tab}-home`) fail(`${tab}: the first sub-page is not home (${tab}-home)`);
      const dash = tabStacks[tab].filter((e) => e.kind === 'dashboard');
      const want = dash.map((e) => slugOf(e.dashboard)).join(',');
      if (pages.slice(1).map((p) => p.id).join(',') !== want) fail(`${tab}: the Homepage pages ${pages.slice(1).map((p) => p.id)} are not the tab's dashboards ${want}`);
      homes[tab] = pages.slice(1).map((p, i) => ({ slug: p.id, title: p.label, icon: p.icon, subtitle: dash[i].subtitle }));
    }
  }
  const redirects = (build.ui.redirects ?? []).map((r) => {
    if (byId.has(r.from)) fail(`redirect from ${r.from}: that dashboard still exists`);
    if (!TABS.includes(r.tab) || r.to !== 'home') fail(`redirect from ${r.from}: only a tab's Homepage is a target`);
    return { slug: slugOf(r.from), tab: r.tab, to: `${r.tab}-home` };
  });
  const bySlug = new Map((services?.services ?? []).map((s) => [s.slug, s]));
  const mesh = {};
  const keep = ['id', 'name', 'category', 'primary', 'priority', 'coverage', 'endpoint', 'fleet_endpoint', 'docs', 'cors', 'paths', 'connector', 'feeds', 'attribution', 'user_endpoint', 'schedule'];
  const slim = sources.sources.map((s) => {
    const o = Object.fromEntries(keep.filter((k) => s[k] !== undefined).map((k) => [k, strip(s[k])]));
    o.auth = { type: s.auth?.type ?? 'none', ...(s.auth?.signup ? { signup: s.auth.signup } : {}) };
    if (s.fleet_endpoint) {
      const svc = bySlug.get(s.fleet_endpoint) ?? fail(`${s.id}: fleet endpoint ${s.fleet_endpoint} is not declared in cloudy-u-containers`);
      if (!svc.mesh) fail(`${s.id}: ${svc.slug} declares no mesh name`);
      mesh[s.fleet_endpoint] = `https://${svc.mesh}`;
    }
    return o;
  });
  // the data files a declared_events source reads (endpoint 'asset:' + path): every one a panel names must be supplied, nothing else is embedded
  const wanted = new Set();
  const assetIds = new Set(sources.sources.filter((s) => s.endpoint === 'asset:').map((s) => s.id));
  for (const d of dashboards.dashboards) for (const p of d.panels) {
    const f = p.fetch;
    if (!f) continue;
    if (assetIds.has(p.source)) wanted.add(f.path);
    for (const fb of f.fallbacks ?? []) if (assetIds.has(fb.source)) wanted.add(fb.path);
  }
  const files = {};
  for (const name of [...wanted].sort()) files[name] = strip(declared[name] ?? fail(`declared data file ${name} is named by a panel but not supplied`));
  return {
    _generated: HEADER,
    app_id: appId,
    mesh,
    tabs: build.ui.bottom_nav.filter((t) => TABS.includes(t)),
    stacks: tabStacks,
    homes,
    redirects,
    sources: slim,
    dashboards: out,
    declared: files,
  };
}

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = listDir('').filter((d) => d.startsWith('ad_Capital-')).find((d) => readRaw(`${d}/data/dashboards.json`)) ?? (() => { throw new Error('no ad_Capital-* folder with data/dashboards.json in the Android repo'); })();
  const nav = JSON.parse(readFileSync(join(root, 'packages/cloudy-ui/nav/nav.json'), 'utf8'));
  const appId = nav.apps.find((a) => a.dir === dir)?.id ?? (() => { throw new Error(`nav.json has no app for ${dir}: run gen-navdata first`); })();
  let doc;
  try {
    doc = buildFinterm({
      sources: JSON.parse(need(`${dir}/data/sources.json`)), dashboards: JSON.parse(need(`${dir}/data/dashboards.json`)), build: JSON.parse(need(`${dir}/build.json`)),
      services: JSON.parse(readFileSync(join(root, 'scripts/fallback-services.json'), 'utf8')), appId,
      // a declared data file is read when the app has it; a panel naming one that is missing fails the render (buildFinterm)
      declared: Object.fromEntries(['central-banks.json'].flatMap((n) => { const t = readRaw(`${dir}/data/${n}`); return t == null ? [] : [[n, JSON.parse(t)]]; })),
    });
  } catch (e) { console.error('FAIL', e.message); process.exit(1); }
  emit(root, { [OUT]: JSON.stringify(doc, null, 2) + '\n', [OUT_APP]: JSON.stringify({ _generated: HEADER, app_id: doc.app_id, tabs: doc.tabs }, null, 2) + '\n' }, 'gen-finterm');
  console.log(`gen-finterm: ${doc.dashboards.length} dashboards, ${doc.sources.length} sources (${dir}, app ${appId})`);
}
