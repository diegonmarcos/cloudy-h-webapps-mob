#!/usr/bin/env node
// gen-cloud-apps.mjs (#1958) — the vendored SuperApp app list (scripts/cloud-apps.json, read by gen-nav.mjs for the shared top nav of the
// service pages) GENERATED from packages/cloudy-ui/nav/nav.json, i.e. aa_cloud-superapp/build.json ui.sections[cloud].tile_groups
// (Cloud > App): same groups, same order, same tiles. Never hand-copied. `--check` fails when the committed file differs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'scripts/cloud-apps.json');
const nav = JSON.parse(readFileSync(join(root, 'packages/cloudy-ui/nav/nav.json'), 'utf8'));
const cloud = nav.superapp.sections.find((s) => s.id === 'cloud');
const out = JSON.stringify({
  _generated: 'GENERATED by scripts/gen-cloud-apps.mjs from packages/cloudy-ui/nav/nav.json (aa_cloud-superapp/build.json ui.sections[cloud].tile_groups) — DO NOT EDIT BY HAND.',
  groups: cloud.tile_groups,
}, null, 2) + '\n';
let cur = null;
try { cur = readFileSync(OUT, 'utf8'); } catch { /* first run */ }
if (process.argv.includes('--check')) {
  if (cur !== out) { console.error('gen-cloud-apps is OUT OF SYNC with nav.json\nFix: node scripts/gen-cloud-apps.mjs && node scripts/gen-nav.mjs'); process.exit(1); }
  console.log('ok: cloud-apps.json current');
} else { writeFileSync(OUT, out); console.log(`wrote ${cloud.tile_groups.length} groups`); }
