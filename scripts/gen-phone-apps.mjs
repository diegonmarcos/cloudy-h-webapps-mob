#!/usr/bin/env node
// gen-phone-apps.mjs — the phone apps' web URLs (Phone > WebApps, #1466), GENERATED from the Android declaration
// aa_cloud-superapp/data/phone-webapps.json (the app -> URL map, same packages as ui.sections[phone].phone_app_groups).
//
//   node scripts/gen-phone-apps.mjs [--android <dir>] [--check]
//
// Writes sites/cloudy-webapps/src/apps/phone-apps/phone-apps.json (src/apps/cloudy-apps/ = the fleet's own apps, src/apps/phone-apps/ = the
// phone apps' web versions). `--check` fails when the committed file differs from a fresh render (CI drift guard, like nav.json).
// A phone app with no known web URL has url null: its tile is drawn greyed and disabled.
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { need, emit, CHECK } from './lib/android-src.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'sites/cloudy-webapps/src/apps/phone-apps/phone-apps.json';
const HEADER = 'GENERATED by scripts/gen-phone-apps.mjs from aa_cloud-superapp/data/phone-webapps.json (diegonmarcos/cloudy-u-android) — DO NOT EDIT. Re-run: node scripts/gen-phone-apps.mjs';

/** Pure: the Android declaration -> the web file. Throws on any contradiction (duplicate package, non-https url, no label). */
export function resolvePhoneApps(decl) {
  const seen = new Set();
  const groups = (decl.groups ?? []).map((g) => ({
    title: g.title,
    tiles: g.apps.map((a) => {
      if (!a.pkg || !a.label) throw new Error(`phone app without pkg/label in group ${g.title}`);
      if (seen.has(a.pkg)) throw new Error(`duplicate phone app ${a.pkg}`);
      seen.add(a.pkg);
      if (a.url != null && !/^https:\/\/[a-z0-9.-]+(\/[A-Za-z0-9._~/-]*)?$/.test(a.url)) throw new Error(`${a.pkg}: url must be https (or null): ${a.url}`);
      return { id: a.pkg, label: a.label, url: a.url ?? null };
    }),
  }));
  return { _generated: HEADER, groups };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = resolvePhoneApps(JSON.parse(need('aa_cloud-superapp/data/phone-webapps.json')));
  emit(root, { [OUT]: JSON.stringify(out, null, 2) + '\n' }, 'gen-phone-apps');
  const tiles = out.groups.flatMap((g) => g.tiles);
  console.log(`${CHECK ? 'ok' : 'wrote'}: ${tiles.length} phone apps, ${tiles.filter((t) => t.url).length} with a web url, ${tiles.filter((t) => !t.url).length} greyed`);
}
